"""Phase 2, step 3: export the trained Decision Tree to C++ for NS-3.

Writes ns3/predictive-model.h: a single inline function made of nested
if/else rules (no ML library at run time). Then compiles a small C++ checker
and confirms it predicts exactly the same class as scikit-learn on every
test sample.

Usage: .venv/bin/python analysis/export_tree.py
"""

import json
import os
import pickle
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import pandas as pd

from build_dataset import FEATURES, LABEL_NAMES

ROOT = Path(__file__).resolve().parent.parent
MODEL = ROOT / "results" / "model" / "decision_tree.pkl"
HEADER = ROOT / "ns3" / "predictive-model.h"
TEST = ROOT / "results" / "model" / "test_predictions.csv"


def tree_to_cpp(tree):
    t = tree.tree_
    names = list(tree.feature_names_in_)
    lines = []

    def uniform_class(node):
        """Class of a subtree whose leaves all agree, else None."""
        if t.children_left[node] == -1:
            return int(t.value[node][0].argmax())
        left = uniform_class(t.children_left[node])
        right = uniform_class(t.children_right[node])
        return left if left is not None and left == right else None

    def emit(node, indent):
        pad = "    " * indent
        cls = uniform_class(node)
        if cls is not None:  # leaf, or a split whose branches give the same answer
            lines.append(f"{pad}return {cls}; // {LABEL_NAMES[cls]}")
            return
        name = names[t.feature[node]]
        # scikit-learn compares float32 values, so the C++ side does the same
        lines.append(f"{pad}if (static_cast<float>({name}) <= {float(t.threshold[node])!r}f)")
        lines.append(f"{pad}{{")
        emit(t.children_left[node], indent + 1)
        lines.append(f"{pad}}}")
        lines.append(f"{pad}else")
        lines.append(f"{pad}{{")
        emit(t.children_right[node], indent + 1)
        lines.append(f"{pad}}}")

    emit(0, 1)
    return lines


def write_header(tree, path=HEADER, note=""):
    # The C++ signature always takes every feature, so TcpPredictive never has to
    # change; features the tree does not use are simply ignored.
    body = "\n".join(tree_to_cpp(tree))
    used = [name for name in FEATURES if f"static_cast<float>({name})" in body]
    args = ",\n                  ".join(
        f"double {name}" if name in used else f"[[maybe_unused]] double {name}" for name in FEATURES)
    header = f"""// Generated by analysis/export_tree.py -- do not edit by hand.
// Decision Tree: depth {tree.get_depth()}, {tree.get_n_leaves()} leaves.
// Trained on: {", ".join(tree.feature_names_in_)}.
// Used by the rules: {", ".join(used)}.
// Predicts the bottleneck congestion level {note or "0.5 s"} ahead from sender-side features.
// Returns 0 = Low, 1 = Medium, 2 = High.

#ifndef PREDICTIVE_MODEL_H
#define PREDICTIVE_MODEL_H

namespace ns3
{{
namespace predictive
{{

enum CongestionLevel
{{
    LOW = 0,
    MEDIUM = 1,
    HIGH = 2
}};

inline int
PredictCongestion({args})
{{
{body}
}}

}} // namespace predictive
}} // namespace ns3

#endif
"""
    path.write_text(header)


def main():
    with open(MODEL, "rb") as f:
        tree = pickle.load(f)
    metrics = json.loads((ROOT / "results" / "model" / "metrics.json").read_text())
    write_header(tree, note=f"{metrics['horizon_s']} s")
    print(f"Wrote {HEADER} (depth {tree.get_depth()}, {tree.get_n_leaves()} leaves)")

    # ---- Verify the C++ rules against scikit-learn ------------------------
    test = pd.read_csv(TEST)
    expected = tree.predict(test[list(tree.feature_names_in_)])
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        test[FEATURES].to_csv(tmp / "features.csv", index=False, header=False)
        checker = f"""#include "{HEADER}"
#include <cstdio>
int main() {{
    FILE* f = std::fopen("{tmp / 'features.csv'}", "r");
    double v[{len(FEATURES)}];
    while (std::fscanf(f, "{','.join(['%lf'] * len(FEATURES))}", {', '.join(f'&v[{i}]' for i in range(len(FEATURES)))}) == {len(FEATURES)}) {{
        std::printf("%d\\n", ns3::predictive::PredictCongestion({', '.join(f'v[{i}]' for i in range(len(FEATURES)))}));
    }}
    return 0;
}}
"""
        (tmp / "check.cc").write_text(checker)
        # Any C++17 compiler works: $CXX if set, else clang++ (macOS), g++ (Linux) or c++
        cxx = os.environ.get("CXX") or next((c for c in ("clang++", "g++", "c++") if shutil.which(c)), None)
        if cxx is None:
            sys.exit("No C++ compiler found (install clang++ or g++, or set CXX)")
        subprocess.run([cxx, "-std=c++17", "-O2", str(tmp / "check.cc"), "-o", str(tmp / "check")], check=True)
        out = subprocess.run([str(tmp / "check")], check=True, capture_output=True, text=True).stdout
    cpp = [int(x) for x in out.split()]
    matches = sum(int(a == b) for a, b in zip(cpp, expected))
    print(f"C++ vs scikit-learn: {matches:,} / {len(expected):,} test samples identical")
    if len(cpp) != len(expected) or matches != len(expected):
        sys.exit("Mismatch between exported C++ rules and the trained model")


if __name__ == "__main__":
    main()
